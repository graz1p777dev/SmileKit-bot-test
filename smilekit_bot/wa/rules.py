# ── Время ──────────────────────────────────────────────────────────────────

BISHKEK = timezone(timedelta(hours=6))
NEUTRAL_AFTER = 30 * 60
DISCOUNT_AFTER = 60 * 60
QUIET_FROM_HOUR = 22
QUIET_TO_HOUR = 9
QUESTIONS_PER_OFFER = 3
# Одно нейтральное напоминание на чат не чаще чем раз в столько — без повторов после каждого «ок».
REMINDER_NEUTRAL_EVERY = 24 * 3600
# Если с последнего сообщения бота прошло больше — напоминать поздно: молчим до ответа клиента.
# Ночной перенос (22:20 → 09:00) в этот срок укладывается.
REMINDER_MAX_AGE = 16 * 3600
# Напоминание не ушло (сбой отправки) — следующая попытка не раньше чем через столько.
REMINDER_RETRY_AFTER = 15 * 60


def is_quiet_hours(now: float) -> bool:
    hour = datetime.fromtimestamp(now, BISHKEK).hour
    return hour >= QUIET_FROM_HOUR or hour < QUIET_TO_HOUR


def bishkek_iso(now: float) -> str:
    return datetime.fromtimestamp(now, BISHKEK).strftime("%Y-%m-%d %H:%M")


def parse_bishkek(value: str) -> float | None:
    try:
        return datetime.strptime(value.strip(), "%Y-%m-%d %H:%M").replace(tzinfo=BISHKEK).timestamp()
    except (ValueError, AttributeError):
        return None


