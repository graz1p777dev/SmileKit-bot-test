def delivery_text(zone: str, place_to: str) -> str | None:
    """Текст доставки для зоны. None — если подставить нечего: клиенту
    никогда не уходит шаблон с пустым местом или скобками."""
    template = _DELIVERY.get(zone)
    if template is None:
        return None
    if "{place}" not in template:
        return template
    place = place_to.strip()
    if not place or any(ch in place for ch in "[]{}<>"):
        return None
    return template.format(place=place)


